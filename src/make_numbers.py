"""Write every number quoted in the report to report/numbers.tex and report/tables/*.tex."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
REP = ROOT / "report"
TAG = {"DK1": "DKa", "DK2": "DKb"}


def fmt(x, nd=1):
    return f"{x:.{nd}f}"


def pval(p):
    return r"<10^{-4}" if p < 1e-4 else f"={p:.3f}" if p >= 1e-3 else f"={p:.1e}"


def main():
    fs = json.loads((RES / "forecast_summary.json").read_text())
    ss = json.loads((RES / "scheduling_summary.json").read_text())
    st = pd.read_csv(RES / "st_point_scores.csv")
    m = {}
    for area, t in TAG.items():
        f, s = fs[area], ss[area]
        dp = f["da_point"]
        m[f"{t}meanY"] = fmt(dp["mean_y"])
        for k, n in [("diurnal", "Diur"), ("rls", "Rls"), ("gbm", "Gbm"), ("energinet_prog_archived", "Prog")]:
            m[f"{t}daMae{n}"] = fmt(dp[k]["MAE"])
            m[f"{t}daRmse{n}"] = fmt(dp[k]["RMSE"])
        m[f"{t}daRed"] = fmt(100 * (1 - dp["rls"]["MAE"] / dp["diurnal"]["MAE"]), 0)
        m[f"{t}daRedGbm"] = fmt(100 * (1 - dp["gbm"]["MAE"] / dp["diurnal"]["MAE"]), 0)
        m[f"{t}dmDiurStat"] = fmt(dp["DM_rls_vs_diurnal"][0])
        m[f"{t}dmDiurP"] = pval(dp["DM_rls_vs_diurnal"][1])
        m[f"{t}dmGbmStat"] = fmt(dp["DM_rls_vs_gbm"][0])
        m[f"{t}dmGbmP"] = pval(dp["DM_rls_vs_gbm"][1])
        g = st[st.area == area].set_index("h")
        for h, n in [(1, "One"), (6, "Six"), (12, "Twelve")]:
            m[f"{t}stPers{n}"] = fmt(g.loc[h, "MAE_persistence"])
            m[f"{t}stRls{n}"] = fmt(g.loc[h, "MAE_rls"])
            m[f"{t}stGbm{n}"] = fmt(g.loc[h, "MAE_gbm"])
        m[f"{t}stRedTwelve"] = fmt(100 * (1 - g.loc[12, "MAE_rls"] / g.loc[12, "MAE_persistence"]), 0)
        pr = f["da_prob"]
        m[f"{t}qsGauss"] = fmt(pr["gauss"]["QS"], 2)
        m[f"{t}qsQr"] = fmt(pr["qr"]["QS"], 2)
        for lev, n in [(80, "Eighty"), (90, "Ninety")]:
            for k, kn in [("gauss", "Gauss"), ("qr", "Qr"), ("aci", "Aci")]:
                m[f"{t}cov{n}{kn}"] = fmt(100 * pr[k][f"cov{lev}"])
                m[f"{t}width{n}{kn}"] = fmt(pr[k][f"width{lev}"], 0)
        for k, kn in [("gauss90", "Gauss"), ("qr90", "Qr"), ("aci90", "Aci")]:
            m[f"{t}top{kn}"] = fmt(100 * f["da_cov_top_quintile"][k])
        yrs = f["da_cov_by_year"]
        m[f"{t}acimin"] = fmt(100 * min(v["aci90"] for v in yrs.values()))
        m[f"{t}acimax"] = fmt(100 * max(v["aci90"] for v in yrs.values()))
        b = s["part_b"]
        m[f"{t}bDays"] = str(b["days"])
        m[f"{t}bFirst"], m[f"{t}bLast"] = b["first_day"], b["last_day"]
        m[f"{t}copCorr"] = fmt(b["mean_copula_corr"], 2)
        for k, n in [("diurnal", "Diur"), ("gbm", "Gbm"), ("rls", "Rls"), ("qr_median", "Qr"),
                     ("scen_mean", "Scen"), ("cvar_b0.5", "Cvar"), ("cvar_b1.0", "CvarOne"), ("oracle", "Oracle")]:
            m[f"{t}bRed{n}"] = fmt(b[k]["reduction_vs_uniform_pct"])
            m[f"{t}bShare{n}"] = fmt(b[k]["share_of_oracle_reduction_pct"], 0)
            m[f"{t}bRegMean{n}"] = fmt(b[k]["regret_mean_kg"], 0)
            m[f"{t}bRegPnf{n}"] = fmt(b[k]["regret_p95_kg"], 0)
            m[f"{t}bRegCvar{n}"] = fmt(b[k]["regret_cvar90_kg"], 0)
        c = s["part_c"]
        m[f"{t}cDays"] = str(c["days"])
        for k, n in [("k1", "One"), ("k2", "Two"), ("k5", "Five"), ("k10", "Ten")]:
            m[f"{t}cShort{n}"] = fmt(c[k]["shortfall_mean_pct"])
            m[f"{t}cShortMax{n}"] = fmt(c[k]["shortfall_max_pct"])
            m[f"{t}cOpt{n}"] = fmt(c[k]["planned_optimism_pct"])
            m[f"{t}cDaysShort{n}"] = fmt(c[k]["days_with_shortfall_pct"], 0)
        m[f"{t}flagged"] = str(json.loads((RES / "forecasts" / f"meta_{area}.json").read_text())["flagged_hours"])
        meta = json.loads((RES / "forecasts" / f"meta_{area}.json").read_text())
        m[f"{t}lamST"], m[f"{t}lamDA"] = str(meta["lambda_ST"]), str(meta["lambda_DA"])
    REP.mkdir(exist_ok=True)
    lines = [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (REP / "numbers.tex").write_text("% generated by src/make_numbers.py -- do not edit\n" + "\n".join(lines) + "\n")

    # table: short-term point scores
    (REP / "tables").mkdir(exist_ok=True)
    rows = []
    for h in range(1, 13):
        cells = [str(h)]
        for area in TAG:
            g = st[(st.area == area) & (st.h == h)].iloc[0]
            cells += [fmt(g.MAE_persistence), fmt(g.MAE_rls), fmt(g.MAE_gbm)]
        rows.append(" & ".join(cells) + r" \\")
    (REP / "tables" / "st_point.tex").write_text("\n".join(rows) + "\n")

    # table: coverage by year
    rows = []
    years = sorted({y for a in TAG for y in fs[a]["da_cov_by_year"]})
    for yv in years:
        cells = [yv]
        for area in TAG:
            v = fs[area]["da_cov_by_year"].get(yv)
            cells += [fmt(100 * v["gauss90"]), fmt(100 * v["qr90"]), fmt(100 * v["aci90"])] if v else ["--"] * 3
        rows.append(" & ".join(cells) + r" \\")
    (REP / "tables" / "cov_year.tex").write_text("\n".join(rows) + "\n")
    print(f"{len(m)} macros written")


if __name__ == "__main__":
    main()
